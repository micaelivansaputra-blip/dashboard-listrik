#!/usr/bin/env python3
"""Build src/modules/drivers/data.js from the invoice rows (meter level) and the daily-file cross-check.
Usage: python3 tools/build_drivers_data.py RAW2.pkl CMP.pkl
  RAW2.pkl  invoice rows with columns Cinema, Month, Year, Type, CT, KwH usage, Tgl Awal, Tgl Akhir, main
  CMP.pkl   per-site table with column daily26 (Sep total from the daily file, kWh)
Run once a month, together with the admits data."""
import json, sys, pathlib
import pandas as pd
raw, cmp_ = pd.read_pickle(sys.argv[1]), pd.read_pickle(sys.argv[2])
raw['mo'] = raw.Month.astype(str).str.lower().str[:3]
s = raw[(raw.mo == 'sep') & raw.Year.isin([2025, 2026]) & raw.main].copy()
s['typ'] = s.Type.str.upper().str.replace(r'[^A-Z]', '', regex=True)
s['days'] = (s['Tgl Akhir'] - s['Tgl Awal']).dt.days + 1
sites = []
for name, grp in s.groupby('Cinema'):
    no, nm = name.split('-', 1)
    meters = []
    for (typ, ct), m in grp.groupby(['typ', 'CT']):
        k = {int(y): round(float(v), 1) for y, v in m.groupby('Year')['KwH usage'].sum().items()}
        meters.append({'t': typ, 'ct': round(float(ct), 2), 'k25': k.get(2025, 0), 'k26': k.get(2026, 0)})
    g25 = grp[(grp.Year == 2025) & grp.days.between(25, 40)]
    d25 = round(float((g25.days * g25['KwH usage']).sum() / g25['KwH usage'].sum()), 1) if len(g25) and g25['KwH usage'].sum() > 0 else None
    dl = cmp_['daily26'].get(name) if name in cmp_.index else None
    sites.append({'no': int(no), 'name': nm.strip().upper(), 'd25': d25, 'daily26': (float(dl) if dl and dl > 0 else None), 'meters': meters})
sites.sort(key=lambda x: x['no'])
data = {'meta': {'periodA': 'Sep 2025', 'periodB': 'Sep 2026', 'assumedDays': 30,
                 'note': 'Meter level invoice kWh (WBP, LWBP, Single times CT). daily26 is the Sep 2026 total of the daily file, a cross-check only.'}, 'sites': sites}
out = pathlib.Path(__file__).parent.parent / 'src/modules/drivers/data.js'
out.write_text('/* Generated by tools/build_drivers_data.py. Do not edit by hand. */\nconst DRIVERS_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\nif (typeof module !== \'undefined\') module.exports = DRIVERS_DATA;\n')
print(out, len(sites), 'sites')
